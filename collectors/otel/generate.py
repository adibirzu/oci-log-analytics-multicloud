"""Generate an OTel Collector Contrib metrics-pull config from a reviewed allowlist.

Usage: python -m collectors.otel.generate --input metrics-pull.yaml [--output out.yaml]

Credentials are never emitted: receivers use the SDK / workload identity chain,
and every secret-like value must be an ${env:NAME} reference.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

import yaml
from jsonschema import Draft202012Validator

SCHEMA_PATH = Path(__file__).with_name("metrics_pull.schema.json")
CLOUD_ORDER = ("aws", "azure", "gcp")
BRIDGE_ENDPOINT = "${env:METRICS_BRIDGE_ENDPOINT}"
APM_ENDPOINT = "${env:OCI_APM_ENDPOINT}"
APM_DATAKEY = "${env:OCI_APM_PRIVATE_DATAKEY}"
AZURE_SUBSCRIPTION = "${env:AZURE_SUBSCRIPTION_ID}"
GCP_PROJECT = "${env:GCP_PROJECT_ID}"

ENV_REF = re.compile(r"^\$\{env:[A-Za-z_][A-Za-z0-9_]*\}$")
SECRET_KEY = re.compile(
    r"access[_-]?key|secret|client[_-]?secret|password|passwd|token(?!_file)|datakey|api[_-]?key",
    re.IGNORECASE,
)
HEADER = "# Generated by collectors/otel/generate.py. Do not edit by hand.\n"


class ConfigError(ValueError):
    """Raised when the allowlist input is invalid or unsafe."""


def load_schema() -> dict[str, Any]:
    return json.loads(SCHEMA_PATH.read_text(encoding="utf-8"))


def _walk_literal_secrets(node: Any, path: str = "") -> None:
    """Refuse any secret-like key whose value is not a bare ${env:NAME} reference."""
    if isinstance(node, dict):
        for key, value in node.items():
            here = f"{path}/{key}"
            if isinstance(key, str) and SECRET_KEY.search(key):
                if not (isinstance(value, str) and ENV_REF.match(value)):
                    raise ConfigError(f"{here}: secret-like key must be an ${{env:NAME}} reference")
            _walk_literal_secrets(value, here)
    elif isinstance(node, list):
        for index, item in enumerate(node):
            _walk_literal_secrets(item, f"{path}[{index}]")


def validate_config(data: Any) -> dict[str, Any]:
    """Validate the allowlist input; raises ConfigError with the first problem found."""
    if not isinstance(data, dict):
        raise ConfigError("top level must be a mapping")
    _walk_literal_secrets(data)
    errors = sorted(
        Draft202012Validator(load_schema()).iter_errors(data),
        key=lambda err: [str(part) for part in err.absolute_path],
    )
    if errors:
        first = errors[0]
        location = "/".join(str(part) for part in first.absolute_path) or "<root>"
        raise ConfigError(f"{location}: {first.message}")
    if not any(cfg["enabled"] for cfg in data["clouds"].values()):
        raise ConfigError("clouds: at least one cloud must be enabled")
    return data


def _receivers_aws(cfg: dict[str, Any]) -> dict[str, Any]:
    interval = f"{cfg['interval']}s"

    def queries() -> list[dict[str, Any]]:
        # Fresh objects per receiver: shared objects would emit YAML anchors.
        return [
            {
                "namespace": metric["namespace"],
                "metric_name": metric["metric_name"],
                "stats": metric.get("stat", "Average"),
            }
            for metric in cfg["metrics"]
        ]

    # One receiver per region: the contrib receiver takes a single region.
    # Identity comes from the SDK chain / web identity env, never from config.
    # Field names verified against otelcol-contrib 0.162.0 (see README.md).
    return {
        f"awscloudwatch/{region}": {
            "region": region,
            "metrics": {
                "collection_interval": interval,
                "period": interval,
                "queries": queries(),
            },
        }
        for region in cfg["regions"]
    }


AZURE_FEDERATED_TOKEN_FILE = "/var/run/secrets/azure/tokens/azure-identity-token"
AZURE_AUTH_EXTENSION = "azureauth"


def _azure_extension(identity: str) -> dict[str, Any]:
    """azureauth extension block; field names verified against otelcol-contrib 0.162.0."""
    if identity == "managed_identity":
        return {"managed_identity": {}}
    # Workload identity: federated token projected by the cluster; no client secret.
    return {
        "workload_identity": {
            "tenant_id": "${env:AZURE_TENANT_ID}",
            "client_id": "${env:AZURE_CLIENT_ID}",
            "federated_token_file": AZURE_FEDERATED_TOKEN_FILE,
        }
    }


def _receivers_azure(cfg: dict[str, Any]) -> dict[str, Any]:
    # azuremonitor shape: {namespace: {MetricName: [aggregations]}}; [] = all aggregations.
    services: dict[str, dict[str, list[str]]] = {}
    for metric in cfg["metrics"]:
        services.setdefault(metric["service"].lower(), {})[metric["metric"]] = list(metric.get("aggregations", []))
    return {
        "azuremonitor": {
            "subscription_ids": [AZURE_SUBSCRIPTION],
            "auth": {"authenticator": AZURE_AUTH_EXTENSION},
            "collection_interval": f"{cfg['interval']}s",
            "services": sorted({m["service"] for m in cfg["metrics"]}),
            "metrics": services,
        }
    }


def _receivers_gcp(cfg: dict[str, Any]) -> dict[str, Any]:
    return {
        "googlecloudmonitoring": {
            "project_id": GCP_PROJECT,
            "collection_interval": f"{cfg['interval']}s",
            "metrics_list": [{"metric_name": name} for name in cfg["metrics"]],
        }
    }


RECEIVER_BUILDERS = {"aws": _receivers_aws, "azure": _receivers_azure, "gcp": _receivers_gcp}
CLOUD_PROVIDER = {"aws": "aws", "azure": "azure", "gcp": "gcp"}
PIPELINE_EXPORTERS = {
    "monitoring": ["otlphttp/bridge"],
    "apm": ["otlphttp/apm"],
    "both": ["otlphttp/bridge", "otlphttp/apm"],
}


def _exporters(sink: str) -> dict[str, Any]:
    exporters: dict[str, Any] = {"otlphttp/bridge": {"endpoint": BRIDGE_ENDPOINT}}
    if sink in ("apm", "both"):
        exporters["otlphttp/apm"] = {
            "metrics_endpoint": f"{APM_ENDPOINT}/20200101/opentelemetry/v1/metrics",
            "headers": {"Authorization": f"dataKey {APM_DATAKEY}"},
        }
    return exporters


def build_config(data: dict[str, Any]) -> dict[str, Any]:
    """Build the collector config dict from a validated allowlist."""
    validate_config(data)
    sink = data.get("metrics_sink", "monitoring")
    receivers: dict[str, Any] = {}
    processors: dict[str, Any] = {
        "memory_limiter": {"check_interval": "1s", "limit_percentage": 80, "spike_limit_percentage": 20},
    }
    pipelines: dict[str, Any] = {}
    extensions: dict[str, Any] = {}
    for cloud in CLOUD_ORDER:
        cfg = data["clouds"].get(cloud)
        if not cfg or not cfg["enabled"]:
            continue
        cloud_receivers = RECEIVER_BUILDERS[cloud](cfg)
        receivers.update(cloud_receivers)
        if cloud == "azure":
            extensions[AZURE_AUTH_EXTENSION] = _azure_extension(cfg["identity"])
        resource = f"resource/{cloud}"
        processors[resource] = {
            "attributes": [{"key": "cloud.provider", "value": CLOUD_PROVIDER[cloud], "action": "upsert"}],
        }
        pipelines[f"metrics/{cloud}"] = {
            "receivers": list(cloud_receivers),
            "processors": ["memory_limiter", resource, "batch"],
            "exporters": list(PIPELINE_EXPORTERS[sink]),
        }
    processors["batch"] = {}
    config: dict[str, Any] = {
        "receivers": receivers,
        "processors": processors,
        "exporters": _exporters(sink),
        "service": {"pipelines": pipelines},
    }
    if extensions:
        config["extensions"] = extensions
        config["service"]["extensions"] = list(extensions)
    _walk_literal_secrets(config)
    return config


def render(data: dict[str, Any]) -> str:
    """Render the collector YAML, with a header naming the identity mode per cloud."""
    config = build_config(data)
    identities = ", ".join(
        f"{cloud}={data['clouds'][cloud]['identity']}"
        for cloud in CLOUD_ORDER
        if cloud in data["clouds"] and data["clouds"][cloud]["enabled"]
    )
    body = yaml.safe_dump(config, sort_keys=False, default_flow_style=False, width=100)
    return f"{HEADER}# identity: {identities} (no static credentials)\n{body}"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate an OTel metrics-pull collector config.")
    parser.add_argument("--input", required=True, type=Path, help="allowlist YAML")
    parser.add_argument("--output", type=Path, help="collector YAML (default: stdout)")
    args = parser.parse_args(argv)
    try:
        data = yaml.safe_load(args.input.read_text(encoding="utf-8"))
        text = render(data)
    except (ConfigError, yaml.YAMLError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    if args.output:
        args.output.write_text(text, encoding="utf-8")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
